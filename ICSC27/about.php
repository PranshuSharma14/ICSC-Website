                </p>
                <br>

                <p>
                    ICSC 2027 continues the legacy of previous editions by serving as a premier international platform for presenting breakthrough research, discussing emerging technologies, and addressing real-world engineering challenges. The conference promotes knowledge exchange, interdisciplinary dialogue, and academia–industry partnerships.
                </p>
                <br>

                <p>
                    ICSC 2027 serves as a global platform for researchers, academicians, and industry professionals
                    to exchange ideas, discuss emerging trends, and showcase innovative research outcomes.
                    As the host of ICSC 2027, the ECE Department at JIIT is committed to ensuring a successful and
                    impactful conference. The conference covers areas including digital signal processing,
                    wireless communication, multimedia systems, network security, and machine learning. We invite participants from academia, industry, and research organizations to join us for an
                    intellectually enriching experience at ICSC 2027.
                </p>


                <!-- Tracks -->
                <h2 class="text-3xl font-bold mt-12">Tracks</h2>
                <br>

                <p><strong>Track 1: Communication Engineering</strong><br>
                    Covers advancements in wireless, optical, satellite, and mobile communication systems. Topics include network protocols, information theory, coding techniques, MIMO systems, 5G/6G technologies, cognitive radio, IoT communication frameworks, and next-generation networking solutions.
                </p>
                <br>

                <p><strong>Track 2: Signal Processing</strong><br>
                    Focuses on digital signal processing, image and video processing, audio and speech processing, biomedical signal analysis, pattern recognition, compression techniques, and AI-assisted signal analytics.
                </p>
                <br>

                <p><strong>Track 3: VLSI and Embedded Technology</strong><br>
                    Encompasses VLSI design methodologies, SoC architectures, FPGA-based systems, ASIC design, embedded platforms, hardware security, testing and verification, low-power design, and hardware accelerators.
                </p>
                <br>

                <p><strong>Track 4: Intelligent Computing and Machine Learning</strong><br>
                    Includes artificial intelligence, machine learning, deep learning, natural language processing, data mining, swarm intelligence, evolutionary computation, explainable AI, and AI applications in engineering systems.
                </p>
                <br>

                <p><strong>Track 5: Sustainable Energy Systems</strong><br>
                    Addresses renewable energy integration, smart grids, power electronics, electric vehicle systems, energy storage technologies, energy management systems, and AI-driven optimization in sustainable power systems.
                </p>
                <br>

                <p><strong>Track 6: Human-Centric Assistive Technologies and Intelligent Robotics</strong><br>
                    Covers intelligent robotics, assistive devices, rehabilitation technologies, wearable systems, healthcare technologies, human–machine interaction, autonomous systems, and socially assistive robotics.
                </p>

